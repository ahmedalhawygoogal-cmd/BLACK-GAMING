export function FaqAccordion() {
  const [openIndex, setOpenIndex] = useState<number | null>(0);

  return (
    <div className="mx-auto mt-12 max-w-3xl space-y-3 sm:mt-16">
      {faqItems.map((item, index) => {
        const isOpen = openIndex === index;

        return (
          <div
            key={item.question}
            className="overflow-hidden rounded-xl border border-white/[0.07] bg-surface/40 backdrop-blur-sm transition-colors duration-200 hover:border-white/[0.12]"
          >
            <button
              type="button"
              onClick={() => setOpenIndex(isOpen ? null : index)}
              aria-expanded={isOpen}
              className="flex w-full items-center justify-between gap-4 px-5 py-5 text-right sm:px-6"
            >
              <span className="text-[14px] font-semibold text-white sm:text-[15px]">
                {item.question}
              </span>
              <ChevronDown
                size={18}
                className={`shrink-0 text-accent-cyan transition-transform duration-300 ${
                  isOpen ? "rotate-180" : ""
                }`}
              />
            </button>

            <div
              className={`grid transition-all duration-300 ease-premium ${
                isOpen ? "grid-rows-[1fr] opacity-100" : "grid-rows-[0fr] opacity-0"
              }`}
            >
              <div className="overflow-hidden">
                <div className="space-y-3 border-t border-white/[0.06] px-5 py-5 text-[13px] leading-8 text-white/55 sm:px-6 sm:text-sm">
                  {item.answer.map((line, i) => (
                    <p key={i}>{line}</p>
                  ))}
                </div>
              </div>
            </div>
          </div>
        );
      })}
    </div>
  );
}
